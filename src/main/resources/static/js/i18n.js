let currentLanguage = localStorage.getItem("tn_culture_lang") || "en";

function setLanguage(lang) {
    if (!I18N_DATA[lang]) {
        lang = "en";
    }
    currentLanguage = lang;
    localStorage.setItem("tn_culture_lang", lang);

    // Update document title and dir
    document.title = (I18N_DATA[lang].appName || "Tamil Nadu Cultural Heritage") + " - " + I18N_DATA[lang].tagline;

    // Apply translations to all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        const translation = I18N_DATA[lang][key] || I18N_DATA.en[key];
        if (translation) {
            if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                el.placeholder = translation;
            } else {
                el.textContent = translation;
            }
        }
    });

    // Update Language Dropdown label
    const langBtn = document.getElementById("selectedLanguageLabel");
    if (langBtn) {
        const langNames = {
            en: "English",
            ta: "தமிழ்",
            hi: "हिन्दी",
            te: "తెలుగు",
            ml: "മലയാളം",
            kn: "ಕನ್ನಡ",
            fr: "Français"
        };
        langBtn.textContent = langNames[lang] || lang.toUpperCase();
    }

    // Trigger re-render of dynamic cultural cards if window.App exists
    if (window.App && typeof window.App.onLanguageChange === "function") {
        window.App.onLanguageChange(lang);
    }
}

function t(key, fallback = "") {
    if (I18N_DATA[currentLanguage] && I18N_DATA[currentLanguage][key]) {
        return I18N_DATA[currentLanguage][key];
    }
    if (I18N_DATA.en && I18N_DATA.en[key]) {
        return I18N_DATA.en[key];
    }
    return fallback || key;
}

window.I18n = {
    setLanguage,
    t,
    getLanguage: () => currentLanguage
};
